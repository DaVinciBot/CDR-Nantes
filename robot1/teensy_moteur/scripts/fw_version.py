"""Writes fw_version.h before each build: which firmware produced a log.

The header defines FW_GIT_DESCRIBE (`git describe --always --dirty`, cut to the
23 characters of the LOG_FW_INFO field) and FW_BUILD_DATE. It lands in the
build folder, never in the sources, and is rewritten only when its content
changes: only the file that includes it (src/main.cpp) is rebuilt.

Called by PlatformIO (extra_scripts = pre:scripts/fw_version.py).
"""

import datetime
import os
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO)


def git_describe(project_dir):
    """Return `git describe` of the project, or "unknown" outside git."""
    try:
        result = subprocess.run(
            ["git", "describe", "--always", "--dirty"],
            cwd=project_dir, capture_output=True, text=True, timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    describe = result.stdout.strip()
    return describe if result.returncode == 0 and describe else "unknown"


out_dir = os.path.join(env.subst("$BUILD_DIR"), "fw_version")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)

describe = git_describe(env.subst("$PROJECT_DIR"))[:23]  # noqa: F821
build_date = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
content = (
    "// Generated by scripts/fw_version.py at each build. Do not edit.\n"
    "#pragma once\n"
    f'#define FW_GIT_DESCRIBE "{describe}"\n'
    f'#define FW_BUILD_DATE "{build_date}"\n'
)

header = os.path.join(out_dir, "fw_version.h")
try:
    with open(header, encoding="utf-8") as current:
        unchanged = current.read() == content
except OSError:
    unchanged = False
if not unchanged:
    with open(header, "w", encoding="utf-8") as out:
        out.write(content)

env.Append(CPPPATH=[out_dir])  # noqa: F821
